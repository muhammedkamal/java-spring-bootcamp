// A program is a list of exact instructions, executed in order.
public class Recipe {
    public static void main(String[] args) {
        int water = 2;      // litres
        int salt = 10;      // grams
        int minutes = 9;

        System.out.println("Boil " + water + " L of water");
        System.out.println("Salt: " + salt + " g");
        System.out.println("Cook: " + minutes + " min");
    }
}
